/** 1 день, 2–4 дні, 5+ днів (11–14 днів). */
const ukDays = (n: number) => {
  const d = n % 10;
  const h = n % 100;
  if (d === 1 && h !== 11) return 'день';
  if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return 'дні';
  return 'днів';
};

